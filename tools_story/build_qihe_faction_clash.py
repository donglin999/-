"""Build the NPC scene data from the responsible design and v3 move contracts."""
import argparse,hashlib,json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
source=ROOT.parent/'xiaojianghu/docs/design/scripts/chapter1-clash.json'
catalog=ROOT.parent/'xiaojianghu/docs/design/martial-review/catalog.json'
private=catalog.parent/'cen-whip.json'
systems=catalog.parent/'martial-systems.json'
d=json.loads(source.read_text());cat=json.loads(catalog.read_text());extra=json.loads(private.read_text());ids=d.pop('skill_ids')
all_skills=cat['skills']+extra['skills'];assert len({s['id'] for s in all_skills})==len(all_skills)
d['skills']={s['id']:{k:s[k] for k in ['id','name','grade','weapon','combat','system_id','art_unlock_level','desc_v4'] if k in s} for s in all_skills if s['id'] in ids}
art_ids={s['system_id'] for s in d['skills'].values()}
d['arts']={s['id']:{k:s[k] for k in ['id','name','grade','skill_ids','mastery']} for s in json.loads(systems.read_text())['systems']+extra['systems'] if s['id'] in art_ids}
assert set(ids)==set(d['skills'])
d['source_sha256']=hashlib.sha256(catalog.read_bytes()).hexdigest();d['scene_source_sha256']=hashlib.sha256(source.read_bytes()).hexdigest()
d['private_source_sha256']=hashlib.sha256(private.read_bytes()).hexdigest()
d['systems_source_sha256']=hashlib.sha256(systems.read_bytes()).hexdigest()
outputs={ROOT/'js/qihe-faction-clash-data.js':"/* Generated by tools_story/build_qihe_faction_clash.py; edit docs/design/scripts/chapter1-clash.json. */\n(function(root){const D="+json.dumps(d,ensure_ascii=False,indent=2)+";if(typeof module==='object'&&module.exports)module.exports=D;else root.QiheClashData=D;})(typeof globalThis!=='undefined'?globalThis:this);\n",ROOT/'art_sources'/d['assetBatch']/'combat-contract.json':json.dumps(d,ensure_ascii=False,indent=2)+'\n'}
for path,body in outputs.items():
    if args.check:assert path.read_text()==body,'Out of date: '+str(path)
    else:path.write_text(body)
print(json.dumps(dict(status='checked' if args.check else 'built',skills=ids,profiles=list(d['profiles']))))
