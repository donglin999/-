"""Compile authored interior footprints/foregrounds, not inferred image collision."""
from pathlib import Path
from PIL import Image,ImageDraw
import json,base64,hashlib,numpy as np
ROOT=Path(__file__).resolve().parents[2];SRC=ROOT/'art_sources/qihe-prologue'
boards=json.loads((SRC/'rooms.json').read_text());result={};manifest={'reuse':'Existing reviewed opening-maps-v4 interiors. Recompiled at 1200×800; no new image generation.','sourceHashes':{}}
for key,m in boards.items():
 im=Image.open(ROOT/m['source']).convert('RGBA');assert list(im.size)==m['sourceSize']
 K=1200/im.width; world=[1200,800]; mask=Image.new('1',(600,400));d=ImageDraw.Draw(mask)
 points=lambda p:[(round(x*K/2),round(y*K/2)) for x,y in p]
 for p in m['walkPolygons']:d.polygon(points(p),fill=1)
 for o in m['obstacles']:d.polygon(points(o['polygon']),fill=0)
 fg=Image.new('RGBA',im.size);fgp=[]
 for o in m['foreground']:
  a=Image.new('L',im.size);ImageDraw.Draw(a).polygon([tuple(p) for p in o['polygon']],fill=255);fg.paste(im,(0,0),a)
  x,y,r,b=a.getbbox();fgp.append([x*K,y*K,(r-x)*K,(b-y)*K,o['sortY']*K])
 bg='m_qihe_'+key;im.save(ROOT/'assets'/f'{bg}.webp',lossless=True);fg.save(ROOT/'assets'/f'{bg}_fg.webp',lossless=True)
 anchors={k:[x*K,y*K] for k,(x,y) in m['anchors'].items()}
 result[key]={'name':m['name'],'bg':bg,'fg':bg+'_fg','fgp':fgp,'worldSize':world,'sourceScale':K,'mask':{'w':600,'h':400,'d':base64.b64encode(np.packbits(np.asarray(mask,dtype=np.uint8).reshape(-1)).tobytes()).decode()},'anchors':anchors,'start':anchors['entry']}
 manifest['sourceHashes'][m['source']]=hashlib.sha256((ROOT/m['source']).read_bytes()).hexdigest()
 overlay=im.copy();ov=Image.new('RGBA',im.size);od=ImageDraw.Draw(ov)
 for o in m['obstacles']:od.polygon([tuple(p) for p in o['polygon']],fill=(255,50,50,100))
 for k,(x,y) in m['anchors'].items():od.ellipse((x-5,y-5,x+5,y+5),fill='#80ffd0');od.text((x+6,y),k,fill='white',stroke_width=1,stroke_fill='black')
 overlay.alpha_composite(ov);overlay.save(SRC/f'{key}-collision.png')
(ROOT/'js/qihe-rooms-data.js').write_text('// Generated by tools_scene/qihe/build_rooms.py\nwindow.QIHE_ROOMS='+json.dumps(result,ensure_ascii=False,separators=(',',':'))+';\n')
manifest['integratedAssets']={str(f.relative_to(ROOT)):{'sha256':hashlib.sha256(f.read_bytes()).hexdigest(),'bytes':f.stat().st_size} for f in (ROOT/'assets').glob('*.webp') if f.name.startswith(('m_qihe_','m_prologue_backhill','bb_prologue_backhill','b_hero_modern','b_ye_initial','b_wilddog','s_opening_hero_modern','s_prologue_wilddog','p_opening_hero_modern','a_opening_hero_modern','cg_p_water'))}
(SRC/'manifest.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n')
print('Compiled five furnished rooms at 1200×800; masks use 2 world units.')
